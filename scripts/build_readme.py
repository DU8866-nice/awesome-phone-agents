def load():
    data = yaml.safe_load((ROOT / "data" / "tools.yaml").read_text(encoding="utf-8"))
    stats_path = ROOT / "data" / "stats.json"
    raw = json.loads(stats_path.read_text(encoding="utf-8")) if stats_path.exists() else {}
    stats = {k.lower(): v for k, v in raw.items()}
    return data, stats


def stars_text(n: int | None) -> str:
    if n is None:
        return "-"
    return f"{n / 1000:.1f}k" if n >= 1000 else str(n)


def sort_items(items, stats):
    return sorted(items, key=lambda i: -(stats.get(i["repo"].lower(), {}).get("stars") or 0))


def status_marks(stat: dict | None, today: dt.date, static: bool = False) -> str:
    if not stat:
        return ""
    out = []
    if (today - dt.date.fromisoformat(stat["created"])).days <= NEW_DAYS:
        out.append("🆕")
    if stat.get("archived"):
        out.append("📦")
    elif not static and (today - dt.date.fromisoformat(stat["pushed"])).days > STALE_DAYS:
        out.append("💤")
    return " ".join(out)


def entry(item, stats, today, lang, static=False):
    t = TEXT[lang]
    s = stats.get(item["repo"].lower())
    name = item["repo"].split("/", 1)[1]
    if name.lower() in DUPLICATE_NAMES:
        name = item["repo"]
    url = f"https://github.com/{item['repo']}"
    head = [f"**[{name}]({url})**", f"★ {stars_text(s['stars'] if s else None)}"]
    icons = [FLAGS[f]["icon"] for f in FLAGS if item.get(f)]
    marks = status_marks(s, today, static)
    if marks:
        icons.append(marks)
    if icons:
        head.append(" ".join(icons))
    meta = []
    if item.get("os"):
        meta.append(" / ".join(OS[o] for o in item["os"]))
    if s:
        meta.append(t["updated"].format(d=s["pushed"][:7]))
    if s and s.get("license") and s["license"] != "NOASSERTION":
        meta.append(s["license"])
    lines = [" · ".join(head), item[lang]]
    if meta:
        lines.append(f"<sub>{' · '.join(meta)}</sub>")
    note = item.get(f"note_{lang}")
    if note:
        lines.append(f"<sub>💡 {note}</sub>")
    return "- " + "<br>".join(lines)


def related_table(items, stats, lang):
    rows = [TEXT[lang]["related_head"]]
    for item in sort_items(items, stats):
        s = stats.get(item["repo"].lower())
        name = item["repo"].split("/", 1)[1]
        rows.append(f"| [{name}](https://github.com/{item['repo']}) | {item[lang]} | {stars_text(s['stars'] if s else None)} | {s['pushed'][:7] if s else '-'} |")
    return "\n".join(rows)


def anchor(cat_id: str) -> str:
    return f"cat-{cat_id}"


def build(lang: str, data, stats, today: dt.date) -> str:
    t = TEXT[lang]
    sections = (ROOT / "data" / f"sections.{lang}.md").read_text(encoding="utf-8")
    parts = dict(re.findall(r"<!-- section:(\w+) -->\n(.*?)(?=\n<!-- section:|\Z)", sections, re.S))
    total = sum(len(c["items"]) for c in data["categories"])
    fetched = max((v.get("fetched", "") for v in stats.values()), default="") or today.isoformat()
    badges = (
        f"[![Stars](https://img.shields.io/github/stars/{REPO}?style=flat-square)](https://github.com/{REPO}) "
        f"[![Last commit](https://img.shields.io/github/last-commit/{REPO}?style=flat-square)](https://github.com/{REPO}/commits) "
        "[![License: CC0-1.0](https://img.shields.io/badge/license-CC0--1.0-lightgrey?style=flat-square)](LICENSE) "
        "[![PRs welcome](https://img.shields.io/badge/PRs-welcome-brightgreen?style=flat-square)](CONTRIBUTING.md)"
    )
    out = [t["header"], "", t["title"], "", badges, "", t["switch"], "", t["tagline"], "", parts["intro"].strip(), "",
           t["count"].format(n=total, date=fetched)]
    toc = list(t["toc_fixed"])
    for c in data["categories"]:
        toc.append(f"- [{c[lang]}](#{anchor(c['id'])})（{len(c['items'])}）" if lang == "zh" else f"- [{c[lang]}](#{anchor(c['id'])}) ({len(c['items'])})")
    toc += t["toc_tail"]
    out += ["", t["toc"], "", *toc, "", '<a id="pick"></a>', parts["pick"].strip(), "", '<a id="rules"></a>', parts["rules"].strip(), "",
            t["legend"].format(new=NEW_DAYS), "", f"> [!NOTE]\n> {t['legend_note']}"]
    for c in data["categories"]:
        out += ["", f'<a id="{anchor(c["id"])}"></a>', f"## {c[lang]}", ""]
        if c.get(f"{lang}_intro"):
            out += [c[f"{lang}_intro"], ""]
        out += [entry(i, stats, today, lang, c.get("static", False)) for i in sort_items(c["items"], stats)]
    out += ["", '<a id="faq"></a>', parts["faq"].strip(), "", '<a id="finder"></a>', parts["finder"].strip(), "",
            '<a id="related"></a>', t["related"], "", related_table(data.get("related", []), stats, lang), "",
            '<a id="contributing"></a>', parts["contributing"].strip(), "", t["star_history"], "",
            f"[![Star History Chart](https://api.star-history.com/svg?repos={REPO}&type=Date)](https://star-history.com/#{REPO}&Date)", ""]
    return "\n".join(out)


def build_catalog(data, stats) -> str:
    """Plain catalog bundled with the finder skill so it works offline."""
    lines = ["# Catalog", "", "Generated from data/tools.yaml. Fields: repo | stars | last push | os | flags (pc = needs a computer, local = can use a local model, byok = needs own model key or account, root = needs root or jailbreak, cn = Chinese-friendly) | description (zh / en)", ""]
    for c in data["categories"]:
        lines += [f"## {c['zh']} / {c['en']}", ""]
        for i in sort_items(c["items"], stats):
            s = stats.get(i["repo"].lower(), {})
            fields = [
                f"https://github.com/{i['repo']}",
                f"stars={s.get('stars', '?')}",
                f"pushed={s.get('pushed', '?')}",
                "os=" + (",".join(i.get("os", [])) or "-"),
                "flags=" + (",".join(f for f in FLAGS if i.get(f)) or "-"),
            ]
            lines.append("- " + " | ".join(fields))
            lines.append(f"  - {i['zh']}")
            lines.append(f"  - {i['en']}")
            if i.get("note_en"):
                lines.append(f"  - caveat: {i['note_en']}")
        lines.append("")
    return "\n".join(lines)


DUPLICATE_NAMES: set[str] = set()


def main():
    data, stats = load()
    names = [i["repo"].split("/", 1)[1].lower() for c in data["categories"] for i in c["items"]]
    DUPLICATE_NAMES.update(n for n in names if names.count(n) > 1)
    today = dt.date.today()
    (ROOT / "README.md").write_text(build("zh", data, stats, today), encoding="utf-8")
    (ROOT / "README.en.md").write_text(build("en", data, stats, today), encoding="utf-8")
    ref = ROOT / "skills" / "phone-agent-finder" / "references"
    ref.mkdir(parents=True, exist_ok=True)
    (ref / "catalog.md").write_text(build_catalog(data, stats), encoding="utf-8")
    missing = [i["repo"] for c in data["categories"] for i in c["items"] if i["repo"].lower() not in stats]
    print(f"built README.md, README.en.md and catalog; entries without stats: {missing or 'none'}")


if __name__ == "__main__":
    main()
